#!/bin/bash
# Makes a throw-away PrintHarbor set-up for the UI tests: pretend Orca profiles (one printer with
# two nozzles, two quality profiles, two filaments), a pretend slicer that writes a small valid
# G-code, a config.json for the given port, and three little models (cube20.stl, bar.stl, cube.obj).
#   tests/ui/mkfixture.sh <folder> <port>
set -e
D=$1; PORT=$2
rm -rf "$D"; mkdir -p "$D/profiles/Acme/machine" "$D/profiles/Acme/process" "$D/profiles/Acme/filament"
cat > "$D/profiles/Acme/machine/mini.json" <<'J'
{"type":"machine","name":"Acme Mini 0.4 nozzle","instantiation":"true","printer_model":"Acme Mini","nozzle_diameter":["0.4"],
 "printable_area":["0x0","220x0","220x220","0x220"],"printable_height":"250","default_print_profile":"0.20mm Standard @Acme",
 "default_filament_profile":["Generic PLA @Acme"],"extruder_colour":["#018001"],"min_layer_height":["0.08"],"max_layer_height":["0.28"]}
J
cat > "$D/profiles/Acme/machine/mini06.json" <<'J'
{"type":"machine","name":"Acme Mini 0.6 nozzle","instantiation":"true","printer_model":"Acme Mini","nozzle_diameter":["0.6"],
 "printable_area":["0x0","220x0","220x220","0x220"],"printable_height":"250","default_print_profile":"0.20mm Standard @Acme"}
J
cat > "$D/profiles/Acme/process/std.json" <<'J'
{"type":"process","name":"0.20mm Standard @Acme","instantiation":"true","layer_height":"0.2","wall_loops":"2","top_shell_layers":"4","bottom_shell_layers":"3",
 "sparse_infill_density":"15%","sparse_infill_pattern":"grid","enable_support":"0","support_type":"normal(auto)","brim_type":"auto_brim","enable_prime_tower":"0",
 "compatible_printers":["Acme Mini 0.4 nozzle","Acme Mini 0.6 nozzle"]}
J
cat > "$D/profiles/Acme/process/draft.json" <<'J'
{"type":"process","name":"0.28mm Draft @Acme","instantiation":"true","layer_height":"0.28","wall_loops":"2","sparse_infill_density":"10%",
 "compatible_printers":["Acme Mini 0.4 nozzle","Acme Mini 0.6 nozzle"]}
J
for m in PLA PETG; do cat > "$D/profiles/Acme/filament/$m.json" <<J
{"type":"filament","name":"Generic $m @Acme","instantiation":"true","filament_type":["$m"],"nozzle_temperature":["210"],"filament_density":["1.24"],
 "compatible_printers":["Acme Mini 0.4 nozzle","Acme Mini 0.6 nozzle"]}
J
done
cat > "$D/orca-slicer" <<'PY'
#!/usr/bin/env python3
# A stand-in for OrcaSlicer: writes a small, valid G-code for the plate it was asked to slice.
# It reads the quality settings it is handed, so the tests can see that they arrive: with tree
# supports on it prints a support block, and it notes the support type and wall count in the file.
import sys, zipfile, os, json
a = sys.argv[1:]; plate = "1"; outdir = "."; out = "out.3mf"; proc = {}
i = 0
while i < len(a):
    if a[i] == "--slice": plate = a[i+1]; i += 1
    elif a[i] == "--load-settings":
        for f in a[i+1].split(";"):
            try:
                d = json.load(open(f))
                if d.get("type") == "process": proc = d
            except Exception: pass
        i += 1
    elif a[i] == "--outputdir": outdir = a[i+1]; i += 1
    elif a[i] == "--export-3mf": out = a[i+1]; i += 1
    i += 1
g = ["; generated by FakeOrca", "; estimated printing time (normal mode) = 12m 34s", "; total filament used [g] = 3.21", "; filament used [g] = 3.21", "; filament used [mm] = 1070.0", "M83", "G28", "T0"]
for layer in range(1, 13):
    z = layer * 0.2
    g += [";LAYER_CHANGE", ";Z:%.2f" % z, ";HEIGHT:0.2", "G1 Z%.2f F600" % z, ";TYPE:Outer wall", ";WIDTH:0.45", "G1 X90 Y90 F6000"]
    for (x, y) in [(130, 90), (130, 130), (90, 130), (90, 90)]: g.append("G1 X%d Y%d E1.2 F1800" % (x, y))
    g += [";TYPE:Sparse infill", "G1 X95 Y95 F6000"]
    for k in range(4): g.append("G1 X%d Y%d E0.9" % (125 if k % 2 == 0 else 95, 95 + (k + 1) * 7))
    if str(proc.get("enable_support")) == "1" and str(proc.get("support_type", "")).startswith("tree"):
        g += [";TYPE:Support", "G1 X140 Y90 F6000"]
        for (x, y) in [(150, 90), (150, 100), (140, 100), (140, 90)]: g.append("G1 X%d Y%d E0.4" % (x, y))
g += ["M104 S0", "; EXECUTABLE_BLOCK_END", "; support_type = %s" % proc.get("support_type", ""), "; wall_loops = %s" % proc.get("wall_loops", "")]
os.makedirs(outdir, exist_ok=True)
with zipfile.ZipFile(os.path.join(outdir, out), "w") as z:
    z.writestr("Metadata/plate_%s.gcode" % plate, "\n".join(g) + "\n")
PY
chmod +x "$D/orca-slicer"
cat > "$D/config.json" <<J
{"listen":"127.0.0.1:$PORT","data_dir":"data","mdns_name":"-","orca_path":"$D/orca-slicer","orca_profiles_dir":"$D/profiles","orca_user_presets_dir":"","slice_timeout_minutes":2}
J
# a 20 mm cube and a bar as binary STL, and a 15 mm cube as OBJ
python3 - "$D" <<'PY'
import struct, sys, os
def stl(path, tris):
    with open(path, "wb") as f:
        f.write(b"\0" * 80); f.write(struct.pack("<I", len(tris)))
        for t in tris:
            f.write(struct.pack("<3f", 0, 0, 0))
            for v in t: f.write(struct.pack("<3f", *v))
            f.write(b"\0\0")
def box(x, y, z):
    v = [(0,0,0),(x,0,0),(x,y,0),(0,y,0),(0,0,z),(x,0,z),(x,y,z),(0,y,z)]
    q = [(0,3,2,1),(4,5,6,7),(0,1,5,4),(1,2,6,5),(2,3,7,6),(3,0,4,7)]
    out = []
    for a,b,c,d in q: out += [(v[a],v[b],v[c]),(v[a],v[c],v[d])]
    return out
d = sys.argv[1]
stl(os.path.join(d, "cube20.stl"), box(20, 20, 20))
stl(os.path.join(d, "bar.stl"), box(60, 10, 8))
v = [(0,0,0),(15,0,0),(15,15,0),(0,15,0),(0,0,15),(15,0,15),(15,15,15),(0,15,15)]
q = [(1,4,3,2),(5,6,7,8),(1,2,6,5),(2,3,7,6),(3,4,8,7),(4,1,5,8)]
with open(os.path.join(d, "cube.obj"), "w") as f:
    f.write("o cube\n")
    for x in v: f.write("v %g %g %g\n" % x)
    for x in q: f.write("f %d %d %d %d\n" % x)
PY
